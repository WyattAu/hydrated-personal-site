#!/usr/bin/env bash
# Sync the built plychart WASM into the site and regenerate the cache-bust
# version constant from the binary's content hash.
#
# Usage: bash scripts/sync-plychart.sh
set -euo pipefail

SITE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLYCHART="${PLYCHART_SRC:-/home/wyatt/dev/src/github.com/WyattAu/plychart}"
PKG="$PLYCHART/crates/plychart/pkg"
DEST="$SITE/apps/site/public/wasm"
OUT="$SITE/apps/site/src/lib/plychart-version.ts"

for f in plychart.js plychart_bg.wasm version.txt; do
  test -f "$PKG/$f" || { echo "missing $PKG/$f — run plychart's scripts/build-wasm.sh first" >&2; exit 1; }
done

cp "$PKG/plychart.js" "$DEST/plychart.js"
cp "$PKG/plychart_bg.wasm" "$DEST/plychart_bg.wasm"

VERSION="$(tr -d '[:space:]' < "$PKG/version.txt")"
cat > "$OUT" <<EOF
/**
 * AUTO-GENERATED by scripts/sync-plychart.sh — do not edit.
 * Content hash of plychart_bg.wasm; consumed by plychart-loader.ts
 * to bust Cloudflare's immutable /wasm/* cache.
 */
export const PLYCHART_VERSION = '$VERSION';
EOF
echo "synced plychart ($VERSION) -> $DEST"
